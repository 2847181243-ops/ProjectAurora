"""Emit the built-in module table from Modules/modules.list.

The Xcode build cannot run the CMake generator, so this small script reads the
same list file. Both paths therefore describe the same set of modules, and the
table still records what the build linked rather than what a manifest claims.
"""
import argparse
import sys
from pathlib import Path


def read_modules(list_path: Path, excluded):
    entries = []
    for number, raw in enumerate(list_path.read_text(encoding="utf-8").splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = [part.strip() for part in line.split("|")]
        if len(parts) != 3 or not all(parts):
            raise SystemExit(f"{list_path}:{number}: expected module_id|entry_symbol|source_dir")
        if parts[0] in excluded:
            continue
        entries.append((parts[0], parts[1]))
    return entries


def render(entries):
    lines = [
        "/* Generated by BuildSystem/generate_builtin_table.py. Do not edit. */",
        '#include "aurora/builtin_modules.h"',
        "",
    ]
    for module_id, symbol in entries:
        lines.append(f'extern "C" const AuroraModuleVTable* {symbol}(void); /* {module_id} */')
    lines.append("")
    lines.append("const AuroraBuiltinModule aurora_builtin_modules[] = {")
    for module_id, symbol in entries:
        lines.append('    {"' + module_id + '", &' + symbol + '},')
    lines.append("};")
    lines.append("")
    lines.append(
        "const size_t aurora_builtin_module_count = "
        "sizeof(aurora_builtin_modules) / sizeof(aurora_builtin_modules[0]);"
    )
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--list", default="Modules/modules.list")
    parser.add_argument("--out", required=True)
    parser.add_argument("--exclude", default="")
    arguments = parser.parse_args()

    excluded = {item.strip() for item in arguments.exclude.split(",") if item.strip()}
    entries = read_modules(Path(arguments.list), excluded)
    output = Path(arguments.out)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(entries), encoding="utf-8")
    print(f"wrote {output} with {len(entries)} module(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
